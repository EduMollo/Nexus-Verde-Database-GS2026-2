CREATE TABLE NV_USUARIO (
 id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 nome VARCHAR2(120 CHAR) NOT NULL,
 papel VARCHAR2(20) NOT NULL CHECK (papel IN ('CIDADAO','EQUIPE')),
 ativo NUMBER(1) DEFAULT 1 NOT NULL CHECK (ativo IN (0,1))
);
COMMENT ON TABLE NV_USUARIO IS 'Nexus Verde GS2026/2 schema-v1';
CREATE TABLE NV_REGIAO (
 id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 nome VARCHAR2(120 CHAR) NOT NULL,
 cidade VARCHAR2(120 CHAR) NOT NULL,
 nivel_risco VARCHAR2(20) NOT NULL CHECK (nivel_risco IN ('BAIXO','MODERADO','ALTO','CRITICO')),
 populacao_afetada NUMBER(10) NOT NULL CHECK (populacao_afetada >= 0),
 CONSTRAINT UK_NV_REGIAO UNIQUE (nome,cidade)
);
CREATE TABLE NV_PONTO_AGUA (
 id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 regiao_id NUMBER REFERENCES NV_REGIAO(id),
 nome VARCHAR2(120 CHAR) NOT NULL,
 cidade VARCHAR2(120 CHAR) NOT NULL,
 endereco VARCHAR2(240 CHAR) NOT NULL,
 tipo VARCHAR2(32) NOT NULL CHECK (tipo IN ('POSTO_DISTRIBUICAO','CAMINHAO_PIPA','RESERVATORIO','ABRIGO')),
 status VARCHAR2(24) NOT NULL CHECK (status IN ('DISPONIVEL','ESTOQUE_BAIXO','ESGOTADO','FECHADO')),
 capacidade_litros NUMBER(10) NOT NULL CHECK (capacidade_litros >= 0),
 estoque_litros NUMBER(10) NOT NULL,
 CONSTRAINT CK_NV_ESTOQUE CHECK (estoque_litros BETWEEN 0 AND capacidade_litros)
);
CREATE TABLE NV_SOLICITACAO (
 id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 solicitante_id NUMBER NOT NULL REFERENCES NV_USUARIO(id),
 regiao_id NUMBER REFERENCES NV_REGIAO(id),
 cadastrada_por_id NUMBER REFERENCES NV_USUARIO(id),
 tipo VARCHAR2(32) NOT NULL CHECK (tipo IN ('FALTA_DE_AGUA','AGUA_CONTAMINADA','ENTREGA_DE_AGUA','OUTRO')),
 descricao VARCHAR2(1000 CHAR) NOT NULL,
 quantidade_pessoas NUMBER(8) NOT NULL CHECK (quantidade_pessoas > 0),
 urgencia VARCHAR2(20) NOT NULL CHECK (urgencia IN ('BAIXA','MEDIA','ALTA','CRITICA')),
 grupo_vulneravel NUMBER(1) NOT NULL CHECK (grupo_vulneravel IN (0,1)),
 endereco VARCHAR2(240 CHAR) NOT NULL,
 cidade VARCHAR2(120 CHAR) NOT NULL,
 latitude NUMBER(10,7) CHECK (latitude BETWEEN -90 AND 90),
 longitude NUMBER(10,7) CHECK (longitude BETWEEN -180 AND 180),
 status VARCHAR2(24) DEFAULT 'ABERTA' NOT NULL CHECK (status IN ('ABERTA','EM_ATENDIMENTO','ATENDIDA','CANCELADA')),
 prioridade NUMBER(3) NOT NULL CHECK (prioridade BETWEEN 0 AND 100),
 criada_em TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
 atualizada_em TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
 excluida_em TIMESTAMP WITH TIME ZONE,
 versao NUMBER(10) DEFAULT 0 NOT NULL
);
CREATE TABLE NV_HISTORICO_STATUS (
 id NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
 solicitacao_id NUMBER NOT NULL REFERENCES NV_SOLICITACAO(id),
 equipe_id NUMBER NOT NULL REFERENCES NV_USUARIO(id),
 status_anterior VARCHAR2(24) NOT NULL,
 status_novo VARCHAR2(24) NOT NULL,
 motivo VARCHAR2(400 CHAR),
 registrada_em TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL
);
CREATE TABLE NV_AUDITORIA (
 id NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
 solicitacao_id NUMBER NOT NULL,
 operacao VARCHAR2(6) NOT NULL CHECK (operacao IN ('INSERT','UPDATE','DELETE')),
 executada_em TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
 usuario_banco VARCHAR2(128) NOT NULL,
 valores_antigos CLOB CHECK (valores_antigos IS JSON),
 valores_novos CLOB CHECK (valores_novos IS JSON)
);
CREATE INDEX IX_NV_SOLIC_REGIAO ON NV_SOLICITACAO(regiao_id);
CREATE INDEX IX_NV_SOLIC_DONO ON NV_SOLICITACAO(solicitante_id);
CREATE INDEX IX_NV_SOLIC_EQUIPE ON NV_SOLICITACAO(cadastrada_por_id);
CREATE INDEX IX_NV_SOLIC_TRIAGEM ON NV_SOLICITACAO(status,excluida_em,prioridade);
CREATE INDEX IX_NV_PONTO_REGIAO ON NV_PONTO_AGUA(regiao_id);
CREATE INDEX IX_NV_HIST_SOLIC ON NV_HISTORICO_STATUS(solicitacao_id,id);
CREATE INDEX IX_NV_HIST_EQUIPE ON NV_HISTORICO_STATUS(equipe_id);
CREATE INDEX IX_NV_AUD_SOLIC ON NV_AUDITORIA(solicitacao_id,id);
